def interp(x, xp, fp): return np.interp(x, xp, fp)


def initial_par_rate():
    fwds = interp(FLOAT_DATES, TODAY_FORWARD_DATES, TODAY_FORWARD_RATES)
    dfs = interp(FLOAT_DATES, TODAY_DISCOUNT_DATES, TODAY_DISCOUNTS)
    pv_float = NOTIONAL * 0.5 * np.sum(fwds * dfs)
    fixed_dfs = interp(FIXED_DATES, TODAY_DISCOUNT_DATES, TODAY_DISCOUNTS)
    annuity = np.sum(fixed_dfs)
    return pv_float / (NOTIONAL * annuity), pv_float, annuity


def revalue_unchanged_curve(fixed_rate):
    rf = FLOAT_DATES[FLOAT_DATES > VALUATION_1Y]; rx = FIXED_DATES[FIXED_DATES > VALUATION_1Y]
    base_df = interp(np.array([VALUATION_1Y]), TODAY_DISCOUNT_DATES, TODAY_DISCOUNTS)[0]
    pv_float = NOTIONAL * .5 * np.sum(interp(rf,TODAY_FORWARD_DATES,TODAY_FORWARD_RATES) * interp(rf,TODAY_DISCOUNT_DATES,TODAY_DISCOUNTS)/base_df)
    pv_fixed = NOTIONAL * fixed_rate * np.sum(interp(rx,TODAY_DISCOUNT_DATES,TODAY_DISCOUNTS)/base_df)
    return pv_float - pv_fixed


def revalue_shifted_curve(fixed_rate):
    rf = FLOAT_DATES[FLOAT_DATES > VALUATION_1Y]; rx = FIXED_DATES[FIXED_DATES > VALUATION_1Y]
    pv_float = NOTIONAL * .5 * np.sum(interp(rf,Y1_FORWARD_DATES,Y1_FORWARD_RATES) * interp(rf,Y1_DISCOUNT_DATES,Y1_DISCOUNTS))
    pv_fixed = NOTIONAL * fixed_rate * np.sum(interp(rx,Y1_DISCOUNT_DATES,Y1_DISCOUNTS))
    return pv_float - pv_fixed


def main():
    fixed, pv_float, annuity = initial_par_rate()
    print(f"Par fixed rate: {100*fixed:.4f}%")
    print(f"1Y NPV, unchanged curve: EUR {revalue_unchanged_curve(fixed):,.2f}")
    print(f"1Y NPV, shifted curve: EUR {revalue_shifted_curve(fixed):,.2f}")
    plt.plot((TODAY_FORWARD_DATES-START_DATE)/365,100*TODAY_FORWARD_RATES,label="Today")
    plt.plot((Y1_FORWARD_DATES-VALUATION_1Y)/365,100*Y1_FORWARD_RATES,label="1Y")
    plt.axhline(100*fixed,ls="--",label="Original fixed rate")
    plt.xlabel("Years from curve date"); plt.ylabel("Rate (%)"); plt.title("EURIBOR 6M forward curves")
    plt.grid(alpha=.3); plt.legend(); plt.tight_layout(); plt.show()

if __name__ == "__main__": main()
